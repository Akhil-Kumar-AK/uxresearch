import {test,expect} from '@playwright/test';
test('complete case study lifecycle persists and updates analytics',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.locator('.study-card')).toHaveCount(6);
 await page.getByRole('button',{name:'New case study',exact:true}).click();
 await page.getByLabel('Case study title').fill('Accessible transit');
 await page.getByLabel('Description',{exact:true}).fill('Help riders confidently plan accessible journeys.');
 await page.getByLabel('Category',{exact:true}).fill('Public transport');
 await page.getByRole('button',{name:'Create case study',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Accessible transit',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Add artifact',exact:true}).click();
 await page.locator('[data-type="persona"]').click();
 await page.getByLabel('Artifact title').fill('Maya, the daily commuter');
 await page.getByLabel('Name & background').fill('Maya uses a wheelchair and commutes every weekday.');
 await page.getByRole('combobox',{name:'Status',exact:true}).selectOption('Done');
 await page.getByRole('button',{name:'Save artifact',exact:true}).click();
 await expect(page.locator('.detail-progress strong')).toHaveText('100%');
 await page.reload();
 await page.getByRole('button',{name:'Accessible transit',exact:true}).click();
 await page.getByRole('button',{name:'Maya, the daily commuter',exact:true}).click();
 await expect(page.getByLabel('Name & background')).toHaveValue('Maya uses a wheelchair and commutes every weekday.');
 await page.getByLabel('Pain points').fill('Elevator outages are difficult to discover.');
 await page.getByRole('button',{name:'Save artifact',exact:true}).click();
 await page.getByRole('button',{name:'Edit details',exact:true}).click();
 await page.getByLabel('Case study title').fill('Inclusive transit');
 await page.getByRole('combobox',{name:'Status',exact:true}).selectOption('Completed');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();
 await page.getByRole('button',{name:'Analytics',exact:true}).click();
 await expect(page.locator('.stat-card').first()).toContainText('07');
 await expect(page.locator('.stat-card').last()).toContainText('02');
 await page.getByRole('button',{name:'Inclusive transit',exact:true}).click();
 await page.getByRole('button',{name:'Delete Maya, the daily commuter',exact:true}).click();
 await page.getByRole('button',{name:'Delete artifact',exact:true}).click();
 await expect(page.locator('.artifact-card')).toHaveCount(0);
 await expect(page.locator('.detail-progress strong')).toHaveText('0%');
 await page.getByRole('button',{name:'Delete case study',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Delete case study',exact:true}).click();
 await expect(page.locator('.study-card')).toHaveCount(6);
 expect(errors).toEqual([]);
});
